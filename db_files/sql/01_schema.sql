-- ---------- lookup / master tables -----------------------------------

CREATE TABLE pincode_area (
    pincode CHAR(6) PRIMARY KEY CHECK (pincode ~ '^[1-9][0-9]{5}$'),
    city    VARCHAR(60) NOT NULL,
    state   VARCHAR(60) NOT NULL
);

CREATE TABLE blood_compat (            -- donor blood group -> recipient blood group
    donor_bg     VARCHAR(3) NOT NULL,
    recipient_bg VARCHAR(3) NOT NULL,
    PRIMARY KEY (donor_bg, recipient_bg)
);

CREATE TABLE hospital (
    hosp_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_id        VARCHAR(20) NOT NULL UNIQUE,
    name          VARCHAR(120) NOT NULL,
    facility_type VARCHAR(20) NOT NULL
                  CHECK (facility_type IN ('transplant_centre','general','clinic')),
    street        VARCHAR(120),
    pincode       CHAR(6) NOT NULL REFERENCES pincode_area(pincode) ON DELETE RESTRICT,
    contact       VARCHAR(10) CHECK (contact ~ '^[6-9][0-9]{9}$')
);

CREATE TABLE specialization (
    spec_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spec_name VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE doctor (
    doctor_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    med_bar_id VARCHAR(20) NOT NULL UNIQUE,
    general_id VARCHAR(20) NOT NULL UNIQUE,
    name       VARCHAR(100) NOT NULL,
    contact    VARCHAR(10) CHECK (contact ~ '^[6-9][0-9]{9}$')
);

CREATE TABLE doctor_spec (
    doctor_id INT NOT NULL REFERENCES doctor(doctor_id) ON DELETE CASCADE,
    spec_id   INT NOT NULL REFERENCES specialization(spec_id) ON DELETE CASCADE,
    PRIMARY KEY (doctor_id, spec_id)
);

CREATE TABLE doctor_hospital (
    doctor_id INT NOT NULL REFERENCES doctor(doctor_id)   ON DELETE RESTRICT,
    hosp_id   INT NOT NULL REFERENCES hospital(hosp_id)   ON DELETE RESTRICT,
    role      VARCHAR(40) NOT NULL,
    join_date DATE NOT NULL CHECK (join_date <= CURRENT_DATE),
    PRIMARY KEY (doctor_id, hosp_id)
);

-- ---------- people ---------------------------------------------------

CREATE TABLE patient (
    patient_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    dob         DATE NOT NULL CHECK (dob <= CURRENT_DATE),
    gender      VARCHAR(5) NOT NULL CHECK (gender IN ('M','F','Other')),
    blood_group VARCHAR(3) NOT NULL
                CHECK (blood_group IN ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
    street      VARCHAR(120),
    pincode     CHAR(6) REFERENCES pincode_area(pincode) ON DELETE RESTRICT,
    notes       TEXT,
    hosp_id     INT NOT NULL REFERENCES hospital(hosp_id) ON DELETE RESTRICT
);

CREATE TABLE donor (
    patient_id     INT PRIMARY KEY REFERENCES patient(patient_id) ON DELETE CASCADE,
    donor_type     VARCHAR(10) NOT NULL CHECK (donor_type IN ('living','deceased')),
    alive_status   VARCHAR(10) NOT NULL CHECK (alive_status IN ('alive','deceased')),
    consent_status VARCHAR(10) NOT NULL DEFAULT 'pending'
                   CHECK (consent_status IN ('pending','given','withdrawn')),
    medical_notes  TEXT,
    CHECK (donor_type = 'living' OR alive_status = 'deceased')
);

CREATE TABLE recipient (
    patient_id    INT PRIMARY KEY REFERENCES patient(patient_id) ON DELETE CASCADE,
    urgency_level SMALLINT NOT NULL CHECK (urgency_level BETWEEN 1 AND 5),  -- 1 = most urgent
    medical_notes TEXT
);

-- ---------- organs ---------------------------------------------------

CREATE TABLE organ_type (
    organ_type_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organ_name             VARCHAR(40) NOT NULL UNIQUE,
    viability_hours        INT CHECK (viability_hours IS NULL OR viability_hours > 0), -- NULL = storable
    living_donation_allowed BOOLEAN NOT NULL
);

CREATE TABLE organ (
    organ_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organ_type_id    INT NOT NULL REFERENCES organ_type(organ_type_id) ON DELETE RESTRICT,
    donor_id         INT NOT NULL REFERENCES donor(patient_id)         ON DELETE RESTRICT,
    full_or_part     VARCHAR(4) NOT NULL CHECK (full_or_part IN ('full','part')),
    harvest_datetime TIMESTAMPTZ NOT NULL CHECK (harvest_datetime <= now() + interval '1 minute'),
    status           VARCHAR(12) NOT NULL DEFAULT 'available'
                     CHECK (status IN ('available','allocated','transplanted','expired')),
    description      TEXT
);

CREATE TABLE waitlist (
    waitlist_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id  INT NOT NULL REFERENCES recipient(patient_id)       ON DELETE RESTRICT,
    organ_type_id INT NOT NULL REFERENCES organ_type(organ_type_id)   ON DELETE RESTRICT,
    hosp_id       INT NOT NULL REFERENCES hospital(hosp_id)           ON DELETE RESTRICT,
    date_added    DATE NOT NULL DEFAULT CURRENT_DATE,
    priority      SMALLINT NOT NULL CHECK (priority BETWEEN 1 AND 5),  -- 1 = highest
    status        VARCHAR(10) NOT NULL DEFAULT 'active'
                  CHECK (status IN ('active','matched','removed','fulfilled'))
);
-- a recipient can wait only once per organ type at a time
CREATE UNIQUE INDEX uq_waitlist_active
    ON waitlist (recipient_id, organ_type_id) WHERE status = 'active';

-- ---------- transplant & recovery -----------------------------------

CREATE TABLE transplant (
    transplant_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organ_id       INT NOT NULL UNIQUE REFERENCES organ(organ_id) ON DELETE RESTRICT,
    recipient_id   INT NOT NULL REFERENCES recipient(patient_id)  ON DELETE RESTRICT,
    hosp_id        INT NOT NULL REFERENCES hospital(hosp_id)      ON DELETE RESTRICT,
    lead_doctor_id INT NOT NULL,
    transplant_date TIMESTAMPTZ NOT NULL,
    outcome        VARCHAR(15) NOT NULL DEFAULT 'pending'
                   CHECK (outcome IN ('successful','complications','failed','pending')),
    -- lead surgeon must actually work at the operating hospital
    FOREIGN KEY (lead_doctor_id, hosp_id)
        REFERENCES doctor_hospital (doctor_id, hosp_id) ON DELETE RESTRICT
);

CREATE TABLE recovery (
    recovery_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transplant_id INT NOT NULL REFERENCES transplant(transplant_id) ON DELETE RESTRICT,
    doctor_id     INT NOT NULL REFERENCES doctor(doctor_id)         ON DELETE RESTRICT,
    checkup_date  DATE NOT NULL,
    status        VARCHAR(12) NOT NULL
                  CHECK (status IN ('stable','improving','critical','rejected','recovered','deceased')),
    description   TEXT
);

-- helpful indexes for FK joins / module queries
CREATE INDEX ix_organ_status      ON organ(status);
CREATE INDEX ix_organ_donor       ON organ(donor_id);
CREATE INDEX ix_waitlist_type_st  ON waitlist(organ_type_id, status);
CREATE INDEX ix_transplant_recip  ON transplant(recipient_id);
CREATE INDEX ix_recovery_tx       ON recovery(transplant_id);

