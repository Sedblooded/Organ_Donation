-- C7 living-donor restriction, C8 consent  (ORGAN insert)
CREATE FUNCTION trg_organ_validate() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE d donor%ROWTYPE; ot organ_type%ROWTYPE;
BEGIN
    SELECT * INTO d  FROM donor WHERE patient_id = NEW.donor_id;
    SELECT * INTO ot FROM organ_type WHERE organ_type_id = NEW.organ_type_id;
    IF d.consent_status <> 'given' THEN
        RAISE EXCEPTION 'C8: donor % has not given consent (status=%)', NEW.donor_id, d.consent_status;
    END IF;
    IF d.donor_type = 'living' AND NOT ot.living_donation_allowed THEN
        RAISE EXCEPTION 'C7: a living donor cannot donate a %', ot.organ_name;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER organ_validate BEFORE INSERT ON organ
    FOR EACH ROW EXECUTE FUNCTION trg_organ_validate();

-- C1-C6, C10  (TRANSPLANT insert)
CREATE FUNCTION trg_transplant_validate() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE o organ%ROWTYPE; ot organ_type%ROWTYPE; d_bg VARCHAR; r_bg VARCHAR; ftype VARCHAR;
BEGIN
    SELECT * INTO o FROM organ WHERE organ_id = NEW.organ_id FOR UPDATE;   -- lock vs concurrent allocation
    SELECT * INTO ot FROM organ_type WHERE organ_type_id = o.organ_type_id;
    SELECT blood_group INTO d_bg FROM patient WHERE patient_id = o.donor_id;
    SELECT blood_group INTO r_bg FROM patient WHERE patient_id = NEW.recipient_id;
    SELECT facility_type INTO ftype FROM hospital WHERE hosp_id = NEW.hosp_id;

    IF o.status NOT IN ('available','allocated') THEN                       -- C3
        RAISE EXCEPTION 'C3: organ % is not available (status=%)', o.organ_id, o.status;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM blood_compat
                   WHERE donor_bg = d_bg AND recipient_bg = r_bg) THEN      -- C1
        RAISE EXCEPTION 'C1: blood group % cannot donate to %', d_bg, r_bg;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM waitlist
                   WHERE recipient_id = NEW.recipient_id
                     AND organ_type_id = o.organ_type_id
                     AND status IN ('active','matched')) THEN               -- C2
        RAISE EXCEPTION 'C2: recipient % is not waitlisted for a %', NEW.recipient_id, ot.organ_name;
    END IF;
    IF ot.viability_hours IS NOT NULL AND
       NEW.transplant_date > o.harvest_datetime + make_interval(hours => ot.viability_hours) THEN  -- C4
        RAISE EXCEPTION 'C4: organ % exceeded its viability window', o.organ_id;
    END IF;
    IF o.donor_id = NEW.recipient_id THEN                                   -- C5
        RAISE EXCEPTION 'C5: donor and recipient cannot be the same person';
    END IF;
    IF ftype <> 'transplant_centre' THEN                                    -- C6
        RAISE EXCEPTION 'C6: hospital % is not a transplant centre', NEW.hosp_id;
    END IF;
    IF NEW.transplant_date < o.harvest_datetime THEN                        -- C10
        RAISE EXCEPTION 'C10: transplant cannot precede organ harvest';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER transplant_validate BEFORE INSERT ON transplant
    FOR EACH ROW EXECUTE FUNCTION trg_transplant_validate();

-- C9 atomic status propagation (same transaction as the INSERT)
CREATE FUNCTION trg_transplant_after() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE waitlist SET status = 'fulfilled'
     WHERE recipient_id = NEW.recipient_id
       AND status IN ('active','matched')
       AND organ_type_id = (SELECT organ_type_id FROM organ WHERE organ_id = NEW.organ_id);
    UPDATE organ SET status = 'transplanted' WHERE organ_id = NEW.organ_id;
    RETURN NEW;
END $$;
CREATE TRIGGER transplant_after AFTER INSERT ON transplant
    FOR EACH ROW EXECUTE FUNCTION trg_transplant_after();

-- C12 / C13 donor guards
CREATE FUNCTION trg_donor_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.alive_status = 'deceased' AND NEW.alive_status = 'alive' THEN    -- C12
        RAISE EXCEPTION 'C12: a deceased donor cannot be marked alive';
    END IF;
    IF NEW.consent_status = 'withdrawn' AND OLD.consent_status <> 'withdrawn'
       AND EXISTS (SELECT 1 FROM organ
                   WHERE donor_id = NEW.patient_id AND status = 'transplanted') THEN  -- C13
        RAISE EXCEPTION 'C13: consent cannot be withdrawn, an organ is already transplanted';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER donor_guard BEFORE UPDATE ON donor
    FOR EACH ROW EXECUTE FUNCTION trg_donor_guard();

-- C10 recovery date ordering
CREATE FUNCTION trg_recovery_validate() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE tdate DATE;
BEGIN
    SELECT (transplant_date AT TIME ZONE 'Asia/Kolkata')::date INTO tdate
      FROM transplant WHERE transplant_id = NEW.transplant_id;
    IF NEW.checkup_date < tdate THEN
        RAISE EXCEPTION 'C10: checkup (%) is before the transplant (%)', NEW.checkup_date, tdate;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER recovery_validate BEFORE INSERT ON recovery
    FOR EACH ROW EXECUTE FUNCTION trg_recovery_validate();

