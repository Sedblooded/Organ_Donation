-- C11: expire perishable organs past their viability window.
-- Call from a scheduler (pg_cron / app cron) every few minutes.
CREATE FUNCTION expire_organs() RETURNS INT LANGUAGE plpgsql AS $$
DECLARE n INT;
BEGIN
    WITH ex AS (
        UPDATE organ o SET status = 'expired'
          FROM organ_type t
         WHERE t.organ_type_id = o.organ_type_id
           AND t.viability_hours IS NOT NULL
           AND o.status IN ('available','allocated')
           AND o.harvest_datetime + make_interval(hours => t.viability_hours) < now()
        RETURNING o.organ_id)
    SELECT count(*) INTO n FROM ex;
    RETURN n;
END $$;

-- A2: ranked, blood-compatible waitlist candidates for one organ.
CREATE FUNCTION find_matches(p_organ_id INT)
RETURNS TABLE (rank BIGINT, waitlist_id INT, recipient_id INT, recipient_name TEXT,
               blood_group TEXT, priority SMALLINT, urgency_level SMALLINT,
               waiting_since DATE, listed_at_hospital TEXT)
LANGUAGE sql STABLE AS $$
    SELECT row_number() OVER (ORDER BY w.priority, r.urgency_level, w.date_added),
           w.waitlist_id, w.recipient_id, p.name::text, p.blood_group::text,
           w.priority, r.urgency_level, w.date_added, h.name::text
      FROM organ o
      JOIN patient dp          ON dp.patient_id = o.donor_id
      JOIN waitlist w          ON w.organ_type_id = o.organ_type_id AND w.status = 'active'
      JOIN recipient r         ON r.patient_id = w.recipient_id
      JOIN patient p           ON p.patient_id = r.patient_id
      JOIN hospital h          ON h.hosp_id = w.hosp_id
      JOIN blood_compat bc     ON bc.donor_bg = dp.blood_group AND bc.recipient_bg = p.blood_group
     WHERE o.organ_id = p_organ_id
       AND o.status = 'available'
     ORDER BY 1;
$$;

